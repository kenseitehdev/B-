size_t bpp_register_inventory_count(BPPTarget t) {
    if (t==BPP_MACOS_ARM64 || t==BPP_LINUX_ARM64) return sizeof arm_inventory/sizeof arm_inventory[0];
    if (t==BPP_LINUX_X64) return sizeof sysv_inventory/sizeof sysv_inventory[0];
    if (t==BPP_WINDOWS_X64) return sizeof win_inventory/sizeof win_inventory[0];
    return 0;
}
const BPPRegisterInfo *bpp_target_register_inventory(BPPTarget t,size_t *n) {
    const BPPRegisterInfo *p=NULL;
    if(t==BPP_MACOS_ARM64||t==BPP_LINUX_ARM64)p=arm_inventory;
    else if(t==BPP_WINDOWS_X64)p=win_inventory;
    else if(t==BPP_LINUX_X64)p=sysv_inventory;
    if(n)*n=bpp_register_inventory_count(t);
    return p;
}
const BPPRegisterInfo *bpp_target_register(BPPTarget t,unsigned id) {
    size_t n=0; const BPPRegisterInfo *a=bpp_target_register_inventory(t,&n);
    for(size_t i=0;i<n;++i) if(a[i].id==id)return &a[i];
    return NULL;
}
const unsigned *bpp_target_allocatable_registers(BPPTarget t,size_t *n) {
    if(t==BPP_MACOS_ARM64||t==BPP_LINUX_ARM64){if(n)*n=sizeof arm_candidates/sizeof arm_candidates[0];return arm_candidates;}
    if(t==BPP_LINUX_X64||t==BPP_WINDOWS_X64){if(n)*n=sizeof x64_candidates/sizeof x64_candidates[0];return x64_candidates;}
    if(n)*n=0;
    return NULL;
}
